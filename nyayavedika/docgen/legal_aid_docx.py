"""Word drafts people can download: the Sec. 12 legal-aid application and the Sec. 479 BNSS release application.

    build_application_docx(data) -> bytes      build_release_docx(data) -> bytes

Generated in memory; nothing personal is stored. Anything not given is written as [to be filled] /
[to be verified]. Rendered with python-docx when installed (requirements.txt), else with the small stdlib
writer in docgen/ooxml.py - same content either way. Works with no LLM key (template facts paragraph).
"""
import io
from datetime import date
from typing import Dict, List, Tuple

from .. import legal_aid
from . import ooxml

APPLICATION_TITLE = "Application for Free Legal Services under Section 12, Legal Services Authorities Act, 1987"
RELEASE_TITLE = "Application under Section 479 of the Bharatiya Nagarik Suraksha Sanhita, 2023 for Release on Bond"
FOOTER = "Draft generated by Nyaya Mitra. Information, not legal advice. Please have it checked by a legal-aid lawyer."
TBF = "[to be filled]"

Blocks = List[Tuple[str, str]]


def render(blocks: Blocks, footer: str = FOOTER) -> bytes:
    try:
        import docx
        from docx.shared import Mm, Pt
    except ImportError:
        return ooxml.build(blocks, footer)
    doc = docx.Document()
    sec = doc.sections[0]
    sec.page_width, sec.page_height = Mm(210), Mm(297)  # A4
    for m in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
        setattr(sec, m, Mm(25))
    normal = doc.styles["Normal"]
    normal.font.name, normal.font.size = ooxml.FONT, Pt(11)
    for kind, text in blocks:
        if kind == "title":
            doc.add_heading(text, level=0)
        elif kind == "heading":
            doc.add_heading(text, level=1)
        elif kind == "bullet":
            doc.add_paragraph(text).paragraph_format.left_indent = Mm(6)
        else:
            doc.add_paragraph(text)
    sec.footer.paragraphs[0].text = footer
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def _v(d: Dict, key: str, default: str = TBF) -> str:
    value = d.get(key)
    return str(value).strip() if value not in (None, "") else default


def application_blocks(data: Dict) -> Blocks:
    """data: {"applicant": {...facts / personal details...}, "problem", "district", "state", "date", "place"}."""
    a = dict(data.get("applicant") or {})
    district, state = data.get("district") or a.get("district"), data.get("state") or a.get("state")
    a.update({k: v for k, v in (("district", district), ("state", state)) if v})
    elig = legal_aid.check_eligibility(a, db=data.get("db"))
    office = elig["where_to_go"]
    addressed = (office["office"] if office.get("district") else f"District Legal Services Authority, {district or TBF}")
    facts = legal_aid.facts_paragraph(data.get("problem") or "")
    applicable = {g["clause"] for g in elig["grounds"]}
    tick = [(clause, desc) for clause, desc in {v[0]: v[1] for v in legal_aid.CATEGORIES.values()}.items()]
    tick.append(("12(h)", f"Annual income not more than {elig['income_limit_note']}"))
    blocks: Blocks = [
        ("title", APPLICATION_TITLE),
        ("para", f"To,\nThe Secretary,\n{addressed}\n{office.get('address') or ''}".rstrip()),
        ("para", "Subject: Request for free legal services under Sections 12 and 13 of the Legal Services Authorities Act, 1987"),
        ("heading", "1. Applicant"),
        ("bullet", f"Name: {_v(a, 'name')}"),
        ("bullet", f"Father's / Husband's name: {_v(a, 'guardian_name')}"),
        ("bullet", f"Age: {_v(a, 'age')}        Gender: {_v(a, 'gender')}"),
        ("bullet", f"Address: {_v(a, 'address')}"),
        ("bullet", f"Phone: {_v(a, 'phone')}"),
        ("bullet", f"Annual family income: {('Rs. ' + legal_aid.inr(a['annual_income'])) if a.get('annual_income') not in (None, '') else TBF}"),
        ("bullet", f"Case number and court (if any): {_v(a, 'case_number')} {('/ ' + a['court']) if a.get('court') else ''}".rstrip()),
        ("heading", "2. Grounds for free legal services (Section 12)"),
        *[("bullet", f"[{'x' if clause in applicable else ' '}] Section {clause}: {desc}") for clause, desc in tick],
        ("heading", "3. Facts"),
        ("para", facts["text"]),
        ("heading", "4. Documents attached"),
        *[("bullet", f"[ ] {d}") for d in elig["documents_needed"]],
        ("heading", "5. Prayer"),
        ("para", "I am unable to engage a lawyer on my own. I request that a panel lawyer be assigned to me free of cost "
                 "and that other necessary legal services be provided."),
        ("heading", "Declaration"),
        ("para", "I declare that the facts stated above are true to the best of my knowledge and belief."),
        ("para", f"Place: {data.get('place') or district or TBF}\nDate: {data.get('date') or date.today().strftime('%d.%m.%Y')}"),
        ("para", "\n\nSignature / Thumb impression of applicant"),
    ]
    return blocks


def build_application_docx(data: Dict) -> bytes:
    return render(application_blocks(data))


def release_blocks(data: Dict) -> Blocks:
    """data: an alert row (case_id, details, draft) or {case_id, custody_since, max_sentence_years, act, section, release_check}."""
    details = data.get("details") or {}
    rc = details.get("release_check") or data.get("release_check") or {}
    blocks: Blocks = [("title", RELEASE_TITLE),
                      ("para", f"IN THE COURT OF {data.get('court') or '[court name] [to be verified]'}"),
                      ("para", f"{data.get('case_id') or '[case number]'}\nState v. [name of accused] [to be verified]")]
    draft = data.get("draft") or ""
    body = [p.strip() for p in draft.split("\n") if p.strip() and not p.strip().startswith(("IN THE COURT", "APPLICATION UNDER", "(Draft"))
            and p.strip() not in (data.get("case_id"), "State v. [name of accused]")]
    if not body:
        body = [f"1. That the applicant/accused has been in judicial custody since {details.get('custody_since') or data.get('custody_since') or '[to be verified]'}"
                f", i.e. for {rc.get('custody_days', '[to be verified]')} days.",
                f"2. That the detention exceeds the Sec. 479 threshold of {rc.get('threshold_days', '[to be verified]')} days.",
                "3. That the delay in trial is not attributable to the applicant [to be verified]."]
    blocks += [("para", p) for p in body]
    blocks.append(("heading", "For the lawyer: verify before filing"))
    blocks += [("bullet", f"[ ] {c}") for c in details.get("checklist") or []]
    blocks.append(("para", "\n[Legal Aid Counsel]                                Place: [ ]     Date: [ ]"))
    return blocks


def build_release_docx(data: Dict) -> bytes:
    return render(release_blocks(data))
